// Dates come off the API as ISO strings. The API stores them as UTC midnight,
// so they are formatted in UTC too — otherwise a user west of GMT sees every
// leave date shifted a day earlier.
const dateFormatter = new Intl.DateTimeFormat("en-GB", {
  day: "2-digit",
  month: "short",
  year: "numeric",
  timeZone: "UTC",
});

const dateTimeFormatter = new Intl.DateTimeFormat("en-GB", {
  day: "2-digit",
  month: "short",
  year: "numeric",
  hour: "2-digit",
  minute: "2-digit",
  timeZone: "UTC",
});

export function formatDate(iso: string) {
  return dateFormatter.format(new Date(iso));
}

export function formatDateTime(iso: string) {
  return dateTimeFormatter.format(new Date(iso));
}

/** ISO string -> the `yyyy-MM-dd` an `<input type="date">` expects. */
export function toDateInputValue(iso: string) {
  return iso.slice(0, 10);
}

